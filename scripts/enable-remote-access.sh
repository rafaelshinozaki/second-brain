#!/usr/bin/env bash
# OPTIONAL: allow agents on OTHER machines (LAN / Tailscale / VPN) to use the
# brain. By default the MCP only accepts connections whose Host header is
# localhost (FastMCP's DNS-rebinding protection). This script:
#   1) publishes Neo4j and the MCP on the given IP (in addition to localhost),
#   2) patches the MCP server so it accepts your remote Host header.
#
# SECURITY: only do this on a TRUSTED private network (e.g. a Tailscale tailnet
# or a home LAN behind NAT). The MCP has no authentication of its own. Never
# expose it directly to the public Internet.
#
# Usage:   bash scripts/enable-remote-access.sh <IP-of-this-machine>
# Example: bash scripts/enable-remote-access.sh 100.100.100.100   (your Tailscale IP)
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$DIR"

IP="${1:-}"
[ -n "$IP" ] || { echo "Usage: bash scripts/enable-remote-access.sh <IP>" >&2; exit 1; }

echo "==> This will expose the brain on $IP (plus localhost) and patch the MCP host check."
read -r -p "Only proceed on a trusted private network. Continue? (type 'yes'): " ok
[ "$ok" = "yes" ] || { echo "Cancelled."; exit 1; }

# 1) Patch the MCP source so FastMCP is built with host='0.0.0.0', which disables
#    the localhost-only Host check. We copy the file out of the image and mount it.
#    Rebuild first (`docker compose up -d --build`) so this copy includes the
#    dual-extraction router from the current image.
echo "==> Extracting and patching graphiti_mcp_server.py"
docker compose up -d graphiti-mcp >/dev/null 2>&1 || true
docker cp second-brain-mcp:/app/mcp/src/graphiti_mcp_server.py config/graphiti_mcp_server.py
python3 - <<'PY'
p = "config/graphiti_mcp_server.py"
s = open(p).read()
old = """mcp = FastMCP(
    'Graphiti Agent Memory',
    instructions=GRAPHITI_MCP_INSTRUCTIONS,
)"""
new = """mcp = FastMCP(
    'Graphiti Agent Memory',
    instructions=GRAPHITI_MCP_INSTRUCTIONS,
    host='0.0.0.0',  # PATCH: disable localhost-only Host check for remote access
)"""
if "host='0.0.0.0'" in s:
    print("already patched")
elif old in s:
    open(p, "w").write(s.replace(old, new, 1))
    print("patched")
else:
    raise SystemExit("Could not find the FastMCP(...) block to patch — image changed?")
PY

# 2) Write a compose override that publishes on $IP and mounts the patched file.
cat > docker-compose.remote.yml <<YAML
# Generated by enable-remote-access.sh — exposes the brain on $IP (trusted network only).
services:
  neo4j:
    ports:
      - "$IP:7474:7474"
      - "$IP:7687:7687"
  graphiti-mcp:
    ports:
      - "$IP:8020:8020"
    volumes:
      - ./config/graphiti_mcp_server.py:/app/mcp/src/graphiti_mcp_server.py:ro
YAML

echo "==> Restarting with remote access enabled"
docker compose -f docker-compose.yml -f docker-compose.remote.yml up -d

cat <<MSG

Done. Agents on your trusted network can now use:
    MCP endpoint:   http://$IP:8020/mcp      (no trailing slash)
    Neo4j Browser:  http://$IP:7474

From now on always bring the stack up with BOTH files:
    docker compose -f docker-compose.yml -f docker-compose.remote.yml up -d
MSG
